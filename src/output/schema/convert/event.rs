//! # `output::schema::convert::event`
//!
//! **Purpose**: Dispatches parser events to schema projection helpers.
//! **Public API**: module-private event projection router
//! **Dependencies**: `output::schema`, `parser::types`
//! **Platform**: `windows-only`
//! **Privilege**: `none`
//! **Line budget**: 140 / 200

use super::{
    dns::{dns_query_line, dns_response_line},
    dpi::{http_request_line, http_response_line, tls_hello_line},
    network::network_event_line,
};
use crate::{
    output::schema::{ErrorLine, OutputLine},
    parser::types::NetEvent,
};

pub(super) fn event_to_line_enriched(
    event: &NetEvent,
    process_name: Option<String>,
    scope_override: Option<String>,
) -> OutputLine {
    match *event {
        NetEvent::Connect {
            timestamp,
            pid,
            proto,
            ref src,
            ref dst,
            bytes_out,
            bytes_in,
        } => network_event_line(
            timestamp,
            pid,
            proto,
            src,
            dst,
            "connect",
            bytes_out,
            bytes_in,
            process_name,
            scope_override,
        ),
        NetEvent::Disconnect {
            timestamp,
            pid,
            proto,
            ref src,
            ref dst,
            bytes_out,
            bytes_in,
        } => network_event_line(
            timestamp,
            pid,
            proto,
            src,
            dst,
            "disconnect",
            bytes_out,
            bytes_in,
            process_name,
            scope_override,
        ),
        NetEvent::Send {
            timestamp,
            pid,
            proto,
            ref src,
            ref dst,
            bytes_out,
            bytes_in,
        } => network_event_line(
            timestamp,
            pid,
            proto,
            src,
            dst,
            "send",
            bytes_out,
            bytes_in,
            process_name,
            scope_override,
        ),
        NetEvent::Recv {
            timestamp,
            pid,
            proto,
            ref src,
            ref dst,
            bytes_out,
            bytes_in,
        } => network_event_line(
            timestamp,
            pid,
            proto,
            src,
            dst,
            "recv",
            bytes_out,
            bytes_in,
            process_name,
            scope_override,
        ),
        NetEvent::RawCapture { .. } => OutputLine::Error(ErrorLine::new(
            "raw capture event cannot be serialized to NDJSON",
        )),
        NetEvent::DnsQuery {
            timestamp,
            pid,
            ref domain,
            query_type,
            ref query_type_name,
        } => dns_query_line(
            timestamp,
            pid,
            domain,
            query_type,
            query_type_name,
            process_name,
        ),
        NetEvent::DnsResponse {
            timestamp,
            pid,
            ref domain,
            query_type,
            ref query_type_name,
            status,
            ref status_name,
            ref result_ips,
            truncated,
        } => dns_response_line(
            timestamp,
            pid,
            domain,
            query_type,
            query_type_name,
            status,
            status_name,
            result_ips,
            truncated,
            process_name,
        ),
        NetEvent::HttpRequest {
            timestamp,
            pid,
            ref src,
            ref dst,
            ref method,
            ref path,
            ref host,
            ref version,
            ref content_type,
            content_length,
        } => http_request_line(
            timestamp,
            pid,
            src,
            dst,
            method,
            path,
            version,
            host.as_deref(),
            content_type.as_deref(),
            content_length,
            process_name,
        ),
        NetEvent::HttpResponse {
            timestamp,
            pid,
            ref src,
            ref dst,
            ref status_line,
            ref host,
            ref version,
            status_code,
            ref content_type,
            content_length,
        } => http_response_line(
            timestamp,
            pid,
            src,
            dst,
            status_line,
            version,
            status_code,
            host.as_deref(),
            content_type.as_deref(),
            content_length,
            process_name,
        ),
        NetEvent::TlsHello {
            timestamp,
            pid,
            ref src,
            ref dst,
            ref sni,
            ref version,
            ref alpn,
            cipher_count,
            extension_count,
        } => tls_hello_line(
            timestamp,
            pid,
            src,
            dst,
            sni.as_deref(),
            version.as_deref(),
            alpn,
            cipher_count,
            extension_count,
            process_name,
        ),
    }
}
