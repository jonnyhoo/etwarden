//! # `output::schema::convert::event::dpi`
//!
//! **Purpose**: Routes application-layer DPI events to HTTP/TLS schema projection.
//! **Public API**: module-private DPI event router
//! **Dependencies**: `output::schema::convert::dpi`, `parser::types`
//! **Platform**: `windows-only`
//! **Privilege**: `none`
//! **Line budget**: 108 / 160

use super::super::{
    dpi::{
        decrypted_http_request_line, decrypted_http_response_line, http_request_line,
        http_response_line, tls_hello_line, tunnel_data_line,
    },
    process::ProcessFields,
};
use crate::{output::schema::OutputLine, parser::types::NetEvent};

pub(super) fn line(event: &NetEvent, process_fields: ProcessFields) -> OutputLine {
    match *event {
        NetEvent::HttpRequest {
            timestamp,
            pid,
            ref src,
            ref dst,
            ref method,
            ref path,
            ref host,
            ref version,
            ref content_type,
            content_length,
        } => http_request_line(
            timestamp,
            pid,
            src,
            dst,
            method,
            path,
            version,
            host.as_deref(),
            content_type.as_deref(),
            content_length,
            None,
            false,
            process_fields,
        ),
        NetEvent::DecryptedHttpRequest {
            timestamp,
            pid,
            ref src,
            ref dst,
            ref method,
            ref path,
            ref host,
            ref version,
            ref headers_base64,
            headers_truncated,
            ref content_type,
            content_length,
            ref content_encoding,
            decoded,
            ref body_base64,
            body_truncated,
        } => decrypted_http_request_line(
            timestamp,
            pid,
            src,
            dst,
            method,
            path,
            version,
            host.as_deref(),
            content_type.as_deref(),
            content_length,
            headers_base64.as_deref(),
            headers_truncated,
            content_encoding.as_deref(),
            decoded,
            body_base64.as_deref(),
            body_truncated,
            process_fields,
        ),
        NetEvent::HttpResponse {
            timestamp,
            pid,
            ref src,
            ref dst,
            ref status_line,
            ref host,
            ref version,
            status_code,
            ref content_type,
            content_length,
        } => http_response_line(
            timestamp,
            pid,
            src,
            dst,
            status_line,
            version,
            status_code,
            host.as_deref(),
            content_type.as_deref(),
            content_length,
            None,
            false,
            process_fields,
        ),
        NetEvent::DecryptedHttpResponse {
            timestamp,
            pid,
            ref src,
            ref dst,
            ref status_line,
            ref host,
            ref version,
            status_code,
            ref headers_base64,
            headers_truncated,
            ref content_type,
            content_length,
            ref content_encoding,
            decoded,
            ref body_base64,
            body_truncated,
        } => decrypted_http_response_line(
            timestamp,
            pid,
            src,
            dst,
            status_line,
            version,
            status_code,
            host.as_deref(),
            content_type.as_deref(),
            content_length,
            headers_base64.as_deref(),
            headers_truncated,
            content_encoding.as_deref(),
            decoded,
            body_base64.as_deref(),
            body_truncated,
            process_fields,
        ),
        NetEvent::TlsHello {
            timestamp,
            pid,
            ref src,
            ref dst,
            ref sni,
            ref version,
            ja3: ref classic_text,
            ja3_hash: ref classic_hash,
            ja3n: ref normalized_text,
            ja3n_hash: ref normalized_hash,
            ja4: ref sorted_fingerprint,
            ja4o: ref original_fingerprint,
            ja4r: ref sorted_raw,
            ja4ro: ref original_raw,
            ref alpn,
            cipher_count,
            extension_count,
        } => tls_hello_line(
            timestamp,
            pid,
            src,
            dst,
            sni.as_deref(),
            version.as_deref(),
            classic_text,
            classic_hash,
            normalized_text,
            normalized_hash,
            sorted_fingerprint,
            original_fingerprint,
            sorted_raw,
            original_raw,
            alpn,
            cipher_count,
            extension_count,
            process_fields,
        ),
        NetEvent::TunnelData {
            timestamp,
            pid,
            ref src,
            ref dst,
            ref direction,
            encrypted,
            ref headers_base64,
            headers_truncated,
            ref payload_base64,
            payload_truncated,
            bytes_seen,
            bytes_captured,
        } => tunnel_data_line(
            timestamp,
            pid,
            src,
            dst,
            direction,
            encrypted,
            headers_base64.as_deref(),
            headers_truncated,
            payload_base64.as_deref(),
            payload_truncated,
            bytes_seen,
            bytes_captured,
            process_fields,
        ),
        _ => super::unsupported_event_line(),
    }
}
